const socialIcons = {
  Appeler: 'assets/icons/telephone.svg',
  WhatsApp: 'assets/icons/whatsapp.svg',
  LinkedIn: 'assets/icons/linkedin.svg'
};

const portraits = document.querySelector('#portraits');
const results = document.querySelector('#results');
const search = document.querySelector('#search');
const opportunity = document.querySelector('#opportunity');
const count = document.querySelector('#count');
const surprise = document.querySelector('#surprise');
const dialog = document.querySelector('#profile');
const content = document.querySelector('#profile-content');
const close = document.querySelector('#close');
const previous = document.querySelector('#previous');
const next = document.querySelector('#next');

const savedOnly = document.querySelector('#saved-only');
const savedCount = document.querySelector('#saved-count');
const saveProfile = document.querySelector('#save-profile');
const selectionLink = document.querySelector('#selection-link');
const selectionKey = 'conversations-inspirantes-mentors-cohorte-2-selection';
const saved = new Set();

try {
  const stored = JSON.parse(localStorage.getItem(selectionKey) || '[]');
  for (const profile of profiles) {
    if (Array.isArray(stored) && stored.includes(profile.id)) saved.add(profile.id);
  }
} catch {
  // La sélection reste disponible pendant la consultation.
}

let visible = profiles;
let current = null;
let lastShown = null;
let opener = null;

function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function nameOf(profile) {
  return profile.first + ' ' + profile.last;
}

function normalize(text) {
  return text.normalize('NFD').replace(/\p{M}/gu, '').toLocaleLowerCase('fr').trim();
}

function profileHash(profile) {
  return '#profil/' + profile.id;
}

function portraitImage(profile) {
  const image = element('img');
  image.src = 'assets/' + profile.id + '.webp';
  image.alt = 'Portrait de ' + nameOf(profile);
  image.decoding = 'async';
  return image;
}

function profileLink(profile, className) {
  const link = element('a', className);
  link.href = profileHash(profile);
  link.addEventListener('click', event => {
    if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    opener = link;
    openProfile(profile);
  });
  return link;
}

for (const profile of profiles) {
  const item = element('li');
  const link = profileLink(profile, 'portrait');
  link.setAttribute('aria-label', 'Découvrir le parcours de ' + nameOf(profile));
  const frame = element('span', 'medallion');
  frame.append(portraitImage(profile));
  link.append(frame, element('span', 'first', profile.first), element('strong', '', profile.last));
  item.append(link);
  portraits.append(item);
}

const opportunityIndex = document.querySelector('#opportunity-index');
for (const category of opportunities) {
  opportunity.add(new Option(category, category));
  const matches = profiles.filter(profile => profile.categories.includes(category));
  const item = element('li');
  const button = element('button', 'opportunity-card');
  button.type = 'button';
  button.append(element('strong', '', category), element('span', '', matches.length + (matches.length === 1 ? ' profil' : ' profils')));
  button.addEventListener('click', () => {
    opportunity.value = category;
    search.value = '';
    savedOnly.checked = false;
    filterProfiles();
    opportunity.focus();
  });
  item.append(button);
  opportunityIndex.append(item);
}

function filterProfiles() {
  const terms = normalize(search.value).split(/\s+/).filter(Boolean);
  visible = profiles.filter(profile => {
    const searchable = normalize([nameOf(profile), profile.domain, ...profile.skills, ...profile.categories].join(' '));
    return terms.every(term => searchable.includes(term))
      && (!opportunity.value || profile.categories.includes(opportunity.value))
      && (!savedOnly.checked || saved.has(profile.id));
  });
  results.replaceChildren();
  for (const profile of visible) {
    const item = element('li');
    const link = profileLink(profile, 'result');
    const arrow = element('span', '', '↗');
    arrow.setAttribute('aria-hidden', 'true');
    const caption = element('div', 'result-caption');
    caption.append(element('strong', '', nameOf(profile)), element('span', 'result-domain', profile.domain));
    const action = element('span', 'result-action', 'Voir le parcours');
    action.append(arrow);
    const categoryText = element('span', 'result-category', profile.categories.join(' · '));
    caption.append(categoryText, action);
    link.append(portraitImage(profile), caption);
    item.append(link);
    results.append(item);
  }
  count.textContent = visible.length === 0
    ? 'Aucun profil ne correspond aux critères.'
    : visible.length + (visible.length === 1 ? ' profil trouvé' : ' profils trouvés');
  savedCount.textContent = saved.size;
  surprise.disabled = visible.length === 0;
  updateNavigation();
}

function updateNavigation() {
  const index = visible.indexOf(current);
  previous.disabled = index <= 0;
  next.disabled = index < 0 || index >= visible.length - 1;
}

function updateSaveButton(profile) {
  const selected = saved.has(profile.id);
  saveProfile.setAttribute('aria-pressed', String(selected));
  saveProfile.textContent = selected ? 'Retirer de ma sélection' : 'Ajouter à ma sélection';
}

function showProfile(profile) {
  current = profile;
  lastShown = profile;
  updateSaveButton(profile);
  const body = element('div', 'profile-body');
  const head = element('div', 'profile-head');
  const heading = element('div');
  const title = element('h2', '', nameOf(profile));
  title.id = 'profile-name';
  title.tabIndex = -1;
  heading.append(title, element('p', 'profile-domain', profile.domain),
    element('p', 'profile-category', profile.categories.join(' · ')));
  head.append(portraitImage(profile), heading);
  body.append(head, element('p', '', profile.intro));

  const skills = element('ul', 'skills');
  skills.setAttribute('aria-label', 'Compétences');
  for (const skill of profile.skills) skills.append(element('li', '', skill));
  body.append(element('h3', 'profile-subtitle', 'Compétences'), skills);

  for (const section of profile.sections) {
    const block = element('section', 'profile-section');
    block.append(element('h3', '', section.title), element('p', '', section.body));
    body.append(block);
  }


  const contacts = element('nav', 'contacts');
  contacts.setAttribute('aria-label', 'Coordonnées du mentor');
  for (const [label, url] of Object.entries(profile.links)) {
    const link = element('a');
    const iconPath = socialIcons[label];
    if (iconPath) {
      const icon = element('img', 'contact-icon');
      icon.src = iconPath;
      icon.alt = '';
      icon.width = 18;
      icon.height = 18;
      link.append(icon);
    }
    const caption = element('span', 'contact-caption');
    caption.append(element('strong', '', label === 'LinkedIn' ? 'Voir le profil LinkedIn' : label));
    if (label === 'Appeler') caption.append(element('span', 'contact-number', profile.phone));
    if (label === 'LinkedIn') link.className = 'contact-professional';
    link.append(caption);
    link.href = url;
    if (url.startsWith('https:')) {
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
    }
    contacts.append(link);
  }
  if (Object.keys(profile.links).length > 0) {
    body.append(element('h3', 'profile-subtitle contact-heading', 'Contacter le mentor'), contacts);
  }
  content.replaceChildren(body);
  updateNavigation();
  if (!dialog.open) dialog.showModal();
  dialog.scrollTop = 0;
  title.focus({ preventScroll: true });
}

function openProfile(profile) {
  const hash = profileHash(profile);
  if (location.hash !== hash) {
    if (dialog.open) history.replaceState(null, '', hash);
    else history.pushState(null, '', hash);
  }
  showProfile(profile);
}

function syncHash() {
  const profile = profiles.find(candidate => profileHash(candidate) === location.hash);
  if (profile) {
    if (profile !== current || !dialog.open) showProfile(profile);
  } else if (dialog.open) {
    dialog.close();
  }
}

function step(direction) {
  const index = visible.indexOf(current);
  if (index >= 0 && visible[index + direction]) openProfile(visible[index + direction]);
}

savedOnly.addEventListener('change', filterProfiles);
selectionLink.addEventListener('click', () => {
  savedOnly.checked = true;
  search.value = '';
  opportunity.value = '';
  filterProfiles();
  savedOnly.focus();
});
saveProfile.addEventListener('click', () => {
  if (!current) return;
  if (saved.has(current.id)) saved.delete(current.id);
  else saved.add(current.id);
  try {
    localStorage.setItem(selectionKey, JSON.stringify([...saved]));
  } catch {
    // Certains navigateurs limitent le stockage des fichiers ouverts localement.
  }
  updateSaveButton(current);
  filterProfiles();
});
search.addEventListener('input', filterProfiles);
opportunity.addEventListener('change', filterProfiles);
document.querySelector('#reset').addEventListener('click', () => {
  search.value = '';
  opportunity.value = '';
  savedOnly.checked = false;
  filterProfiles();
  search.focus();
});
surprise.addEventListener('click', () => {
  if (visible.length === 0) return;
  const pool = visible.length > 1 ? visible.filter(profile => profile !== lastShown) : visible;
  opener = surprise;
  openProfile(pool[Math.floor(Math.random() * pool.length)]);
});
close.addEventListener('click', () => dialog.close());
previous.addEventListener('click', () => step(-1));
next.addEventListener('click', () => step(1));
dialog.addEventListener('close', () => {
  if (location.hash.startsWith('#profil/')) history.replaceState(null, '', location.href.split('#')[0]);
  const fallback = !opener?.isConnected && current && [...portraits.querySelectorAll('a')].find(link => link.hash === profileHash(current));
  current = null;
  const target = opener?.isConnected ? opener : fallback || portraits.querySelector('a');
  opener = null;
  target?.focus({ preventScroll: true });
});
window.addEventListener('popstate', syncHash);
window.addEventListener('hashchange', syncHash);

filterProfiles();
syncHash();
